-- Migration to support users having different roles in different hospitals

-- 1. Create the new role assignment table
CREATE TABLE user_role_assignment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    hospital_id BIGINT, -- NULL means global role (e.g. SUPER_ADMIN)
    role_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_assignment_user FOREIGN KEY (user_id) REFERENCES user_account(id),
    CONSTRAINT fk_assignment_hospital FOREIGN KEY (hospital_id) REFERENCES hospital(id),
    CONSTRAINT fk_assignment_role FOREIGN KEY (role_id) REFERENCES role(id)
);

-- 2. Migrate existing data from the previous many-to-many table
-- We assume current roles belong to the user's hospital (if it was still there) 
-- or we use the hospital_id that was previously on the user_account.
-- Since we just ran V3, we have user_role (user_id, role_id).
-- We'll try to recover the hospital_id if possible, but in this refactor 
-- we'll just move them as global roles first or link them to their original hospital.
INSERT INTO user_role_assignment (user_id, hospital_id, role_id, created_at, updated_at)
SELECT ur.user_id, ua.hospital_id, ur.role_id, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM user_role ur
JOIN user_account ua ON ur.user_id = ua.id;

-- 3. Drop the old user_role table
DROP TABLE user_role;

-- 4. Remove hospital_id from user_account as it's now per-role
ALTER TABLE user_account DROP COLUMN hospital_id;
