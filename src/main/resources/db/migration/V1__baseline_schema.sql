-- Core Phase 1 schema for the HMS backend.
-- The design keeps every operational table hospital-scoped so tenant isolation is enforced in the backend.

create table if not exists hospital (
    id bigint generated by default as identity primary key,
    name varchar(255) not null,
    code varchar(50) not null unique,
    address varchar(1000),
    status varchar(20) not null,
    created_at timestamp not null,
    updated_at timestamp not null
);

create table if not exists role (
    id bigint generated by default as identity primary key,
    code varchar(50) not null unique,
    name varchar(100) not null,
    description varchar(255),
    is_system boolean not null,
    is_active boolean not null,
    created_at timestamp not null,
    updated_at timestamp not null
);

create table if not exists user_account (
    id bigint generated by default as identity primary key,
    hospital_id bigint not null,
    username varchar(100) not null unique,
    password_hash varchar(255) not null,
    role_id bigint not null,
    is_active boolean not null,
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint fk_user_account_hospital foreign key (hospital_id) references hospital(id),
    constraint fk_user_account_role foreign key (role_id) references role(id)
);

create index if not exists idx_user_account_hospital on user_account(hospital_id);

create table if not exists patient (
    id bigint generated by default as identity primary key,
    hospital_id bigint not null,
    full_name varchar(255) not null,
    gender varchar(20),
    dob date,
    phone varchar(20),
    address varchar(1000),
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint fk_patient_hospital foreign key (hospital_id) references hospital(id)
);

create index if not exists idx_patient_hospital on patient(hospital_id);

create table if not exists doctor (
    id bigint generated by default as identity primary key,
    hospital_id bigint not null,
    full_name varchar(255) not null,
    gender varchar(20),
    dob date,
    phone varchar(20),
    specialization varchar(255) not null,
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint fk_doctor_hospital foreign key (hospital_id) references hospital(id)
);

create index if not exists idx_doctor_hospital on doctor(hospital_id);

create table if not exists nurse (
    id bigint generated by default as identity primary key,
    hospital_id bigint not null,
    full_name varchar(255) not null,
    gender varchar(20),
    dob date,
    phone varchar(20),
    department varchar(255) not null,
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint fk_nurse_hospital foreign key (hospital_id) references hospital(id)
);

create index if not exists idx_nurse_hospital on nurse(hospital_id);

create table if not exists appointment (
    id bigint generated by default as identity primary key,
    hospital_id bigint not null,
    patient_id bigint not null,
    doctor_id bigint not null,
    appointment_time timestamp not null,
    status varchar(30) not null,
    notes varchar(1000),
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint fk_appointment_hospital foreign key (hospital_id) references hospital(id),
    constraint fk_appointment_patient foreign key (patient_id) references patient(id),
    constraint fk_appointment_doctor foreign key (doctor_id) references doctor(id)
);

create index if not exists idx_appointment_hospital on appointment(hospital_id);
create index if not exists idx_appointment_time on appointment(hospital_id, appointment_time);

create table if not exists billing (
    id bigint generated by default as identity primary key,
    hospital_id bigint not null,
    patient_id bigint not null,
    source_type varchar(30) not null,
    status varchar(30) not null,
    total_amount numeric(12, 2) not null,
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint fk_billing_hospital foreign key (hospital_id) references hospital(id),
    constraint fk_billing_patient foreign key (patient_id) references patient(id)
);

create index if not exists idx_billing_hospital on billing(hospital_id);

create table if not exists billing_item (
    id bigint generated by default as identity primary key,
    hospital_id bigint not null,
    billing_id bigint not null,
    item_name varchar(255) not null,
    amount numeric(12, 2) not null,
    quantity integer not null,
    subtotal numeric(12, 2) not null,
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint fk_billing_item_hospital foreign key (hospital_id) references hospital(id),
    constraint fk_billing_item_billing foreign key (billing_id) references billing(id)
);

create index if not exists idx_billing_item_hospital on billing_item(hospital_id);

create table if not exists item (
    id bigint generated by default as identity primary key,
    hospital_id bigint not null,
    name varchar(255) not null,
    category varchar(100),
    unit varchar(50),
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint fk_item_hospital foreign key (hospital_id) references hospital(id)
);

create index if not exists idx_item_hospital on item(hospital_id);

create table if not exists inventory_stock (
    id bigint generated by default as identity primary key,
    hospital_id bigint not null,
    item_id bigint not null,
    quantity numeric(12, 2) not null,
    last_updated timestamp not null,
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint fk_inventory_stock_hospital foreign key (hospital_id) references hospital(id),
    constraint fk_inventory_stock_item foreign key (item_id) references item(id),
    constraint uq_inventory_stock unique (hospital_id, item_id)
);

create index if not exists idx_inventory_stock_hospital on inventory_stock(hospital_id);

create table if not exists inventory_transaction (
    id bigint generated by default as identity primary key,
    hospital_id bigint not null,
    item_id bigint not null,
    type varchar(20) not null,
    quantity numeric(12, 2) not null,
    reference varchar(100),
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint fk_inventory_tx_hospital foreign key (hospital_id) references hospital(id),
    constraint fk_inventory_tx_item foreign key (item_id) references item(id)
);

create index if not exists idx_inventory_transaction_hospital on inventory_transaction(hospital_id);

create table if not exists medicine (
    id bigint generated by default as identity primary key,
    hospital_id bigint not null,
    name varchar(255) not null,
    composition varchar(255),
    manufacturer varchar(255),
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint fk_medicine_hospital foreign key (hospital_id) references hospital(id)
);

create index if not exists idx_medicine_hospital on medicine(hospital_id);

create table if not exists pharmacy_stock (
    id bigint generated by default as identity primary key,
    hospital_id bigint not null,
    medicine_id bigint not null,
    batch_number varchar(100) not null,
    expiry_date date,
    quantity integer not null,
    price numeric(12, 2) not null,
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint fk_pharmacy_stock_hospital foreign key (hospital_id) references hospital(id),
    constraint fk_pharmacy_stock_medicine foreign key (medicine_id) references medicine(id)
);

create index if not exists idx_pharmacy_stock_hospital on pharmacy_stock(hospital_id);
create index if not exists idx_pharmacy_stock_expiry on pharmacy_stock(hospital_id, medicine_id, expiry_date);

create table if not exists prescription (
    id bigint generated by default as identity primary key,
    hospital_id bigint not null,
    patient_id bigint not null,
    doctor_id bigint not null,
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint fk_prescription_hospital foreign key (hospital_id) references hospital(id),
    constraint fk_prescription_patient foreign key (patient_id) references patient(id),
    constraint fk_prescription_doctor foreign key (doctor_id) references doctor(id)
);

create index if not exists idx_prescription_hospital on prescription(hospital_id);

create table if not exists prescription_item (
    id bigint generated by default as identity primary key,
    hospital_id bigint not null,
    prescription_id bigint not null,
    medicine_id bigint not null,
    dosage varchar(255) not null,
    duration varchar(255) not null,
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint fk_prescription_item_hospital foreign key (hospital_id) references hospital(id),
    constraint fk_prescription_item_prescription foreign key (prescription_id) references prescription(id),
    constraint fk_prescription_item_medicine foreign key (medicine_id) references medicine(id)
);

create index if not exists idx_prescription_item_hospital on prescription_item(hospital_id);

create table if not exists audit_log (
    id bigint generated by default as identity primary key,
    hospital_id bigint not null,
    entity_name varchar(100) not null,
    entity_id bigint not null,
    action varchar(50) not null,
    performed_by bigint,
    details varchar(4000),
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint fk_audit_hospital foreign key (hospital_id) references hospital(id)
);

create index if not exists idx_audit_log_hospital on audit_log(hospital_id, created_at);
